// Helper to generate chart timeline points
const generate30DayTrend = (baseTraffic: number, baseLeads: number, baseSpend: number, roasMultiplier: number) => {
  const points = [];
  const days = 30;
  for (let i = days; i >= 1; i--) {
    const dayDate = new Date();
    dayDate.setDate(dayDate.getDate() - i);
    const dateStr = dayDate.toLocaleDateString('en-US', { month: 'short', day: 'numeric' });
    
    // Controlled seasonal variance
    const weekdayFactor = dayDate.getDay() === 0 || dayDate.getDay() === 6 ? 0.75 : 1.12;
    const variance = (Math.sin(i * 0.45) * 0.15) + (Math.cos(i * 0.2) * 0.1);
    
    const organic = Math.round((baseTraffic * 0.45 * (1 + variance)) * weekdayFactor);
    const paid = Math.round((baseTraffic * 0.32 * (1 + variance * 0.8)) * weekdayFactor);
    const direct = Math.round((baseTraffic * 0.14 * (1 + variance * 0.5)) * weekdayFactor);
    const social = Math.round((baseTraffic * 0.06 * (1 + variance * 0.6)) * weekdayFactor);
    const referral = Math.round((baseTraffic * 0.03 * (1 + variance * 0.3)) * weekdayFactor);
    const total = organic + paid + direct + social + referral;
    
    const leads = Math.max(1, Math.round((baseLeads / days) * (1 + variance) * weekdayFactor));
    const cost = Math.round((baseSpend / days) * (1 + variance * 0.5));
    const revenue = Math.round(cost * roasMultiplier * (1 + variance * 0.6));

    points.push({
      date: dateStr,
      label: dateStr,
      organic,
      paid,
      direct,
      social,
      referral,
      total,
      leads,
      cost,
      revenue,
    });
  }
  return points;
};

